const lines = data.trim().split('\n');

const generateFallbackEmail = (name) => {
    const slug = name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/\s+/g, '.');
    // Random string to avoid conflicts
    const random = Math.floor(Math.random() * 10000);
    return `${slug}.pendente${random}@fazendasaobento.com.br`;
};

async function importMembers() {
    for (const [index, line] of lines.entries()) {
        const columns = line.split('\t');
        
        // Structure is: Name | Status | Phone | Email | Address
        const fullName = columns[0]?.trim();
        const memberStatus = columns[1]?.trim() === 'ATIVO' ? 'Ativo' : 'Inativo';
        const phone = columns[2]?.trim() || '';
        let email = columns[3]?.trim();
        // Remove spaces inside emails (found "Crstinadecat@ hotmail.com")
        if (email) email = email.replace(/\s+/g, '').toLowerCase(); 
        const address = columns[4]?.trim() || '';

        if (!email) {
            email = generateFallbackEmail(fullName);
        }

        const payload = {
            action: 'register',
            email: email,
            full_name: fullName,
            role: 'member',
            member_status: memberStatus,
            send_email: false, // DO NOT spam them yet!
            phone: phone,
            address: address
        };

        try {
            console.log(`[${index + 1}/${lines.length}] Registering ${fullName}...`);
            const response = await fetch('https://nxnxqwmqeujaiuqajmhc.supabase.co/functions/v1/admin-register-user', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(payload)
            });

            const result = await response.json();
            if (!response.ok) {
                console.error(`ERROR for ${fullName}:`, result);
            } else {
                console.log(`Success: ${fullName}`);
            }
        } catch (err) {
            console.error(`FETCH ERROR for ${fullName}:`, err.message);
        }
    }
    console.log("IMPORT COMPLETE!");
}

